MSN = "01J0000000000000000000MSN1"
_REPO = Path(__file__).resolve().parent.parent
_VALID = Path(pc.__file__).resolve().parent / "fixtures" / "rows" / "valid"


def _lane_row() -> Dict[str, Any]:
    return {
        "event_id": "01J0000000000000000000F001",
        "mission_slug": "041-demo",
        "wp_id": "WP01",
        "from_lane": "planned",
        "to_lane": "claimed",
        "at": "2026-01-01T00:00:00+00:00",
        "actor": {"role": "implementer", "profile": "p", "tool": "claude", "model": "m"},
        "force": False,
        "execution_mode": "worktree",
        "reason": None,
        "review_ref": None,
        "evidence": None,
    }


def test_diary_row_inverts_the_lane_mapping() -> None:
    row = _lane_row()
    event = upcast(row, UpcastContext(missionid=MSN)).row
    assert diary_row(event) == dict(row, mission_id=MSN)
    plain = dict(row, actor="claude")
    assert diary_row(upcast(plain, UpcastContext(missionid=MSN)).row) == dict(plain, mission_id=MSN)


def test_diary_row_inverts_the_annotation_mapping() -> None:
    row = {
        "event_id": "01J0000000000000000000A001",
        "at": "2026-01-01T00:00:02+00:00",
        "wp_id": "WP01",
        "actor": "claude",
        "kind": "annotation",
        "delta": {"subtasks": {"T001": "done"}},
    }
    assert diary_row(upcast(row, UpcastContext(missionid=MSN)).row) == row


def test_diary_row_refuses_other_types() -> None:
    with pytest.raises(ValueError):
        diary_row({"type": "ai.spec-kitty.mission.created.v1"})


def test_validator_profiles_and_codes() -> None:
    event = upcast(_lane_row(), UpcastContext(missionid=MSN)).row
    assert validate_cloudevent(event) == []
    write = validate_cloudevent(event, profile="write")
    assert {issue.path for issue in write} == {""} and {i.keyword for i in write} == {"required"}
    assert (
        validate_cloudevent(dict(event, lamportclock=1, nodeid="0123456789ab"), profile="write")
        == []
    )
    mismatch = validate_cloudevent(dict(event, missionid="01J0000000000000000000MSN2"))
    assert [issue.code for issue in mismatch] == ["SOURCE_MISMATCH"]
    stray = validate_cloudevent(dict(event, data=dict(event["data"], zz=1)))
    assert [(i.code, i.path, i.keyword) for i in stray] == [
        ("SCHEMA_VIOLATION", "/data", "additionalProperties")
    ]
    assert [i.code for i in validate_cloudevent([event])] == ["NOT_AN_OBJECT"]
    assert [i.code for i in validate_cloudevent(dict(event, type="ai.spec-kitty.nope.v1"))] == [
        "UNREGISTERED_TYPE"
    ]
    with pytest.raises(ValueError):
        validate_cloudevent(event, profile="other")


def test_a_work_package_type_without_its_work_package_is_named() -> None:
    envelope = json.loads((_VALID / "mission.started.v1.json").read_text(encoding="utf-8"))
    row = dict(envelope["transport_row"], event_type="WPStatusChanged", payload={"to_lane": "done"})
    assert upcast(row).codes == (IssueCode.MISSING_MEMBER,)


@pytest.mark.parametrize("path", sorted(_VALID.glob("*.json")), ids=lambda p: p.stem)
def test_every_transport_row_is_a_strict_3_0_0_envelope_and_upcasts_to_its_input(
    path: Path,
) -> None:
    fixture = json.loads(path.read_text(encoding="utf-8"))
    if "transport_row" not in fixture:
        pytest.skip("not a transport-only type")
    row = fixture["transport_row"]
    validate_strict_envelope(row)
    event = upcast(row).row
    expected = fixture["input"]
    assert {k: v for k, v in event.items() if k in expected} == expected
    assert set(event) - set(expected) == {
        "buildid",
        "correlationid",
        "projectuuid",
        "projectslug",
        "datatier",
    }


def test_the_committed_corpus_is_what_the_generator_writes() -> None:
    result = subprocess.run(
        [sys.executable, str(_REPO / "scripts" / "generate_upcast_corpus.py"), "--check"],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.parametrize("path", sorted(_VALID.glob("*.json")), ids=lambda p: p.stem)
def test_every_cli_legacy_row_upcasts_to_its_input(path: Path) -> None:
    """FR-005a against an independent source: the producer fixtures pair each legacy row with
    the CloudEvent it is (authored for #6185, not generated by the upcaster)."""
    fixture = json.loads(path.read_text(encoding="utf-8"))
    if "legacy_row" not in fixture:
        pytest.skip("a transport-only type: see the transport-row test")
    expected = fixture["input"]
    source = expected["source"]
    context = UpcastContext(
        missionid=expected.get("missionid"),
        missionslug=expected.get("missionslug"),
        projectuuid=source.rsplit("/", 1)[1]
        if source.startswith("/spec-kitty/projects/")
        else None,
    )
    event = upcast(fixture["legacy_row"], context, strict=True).row
    # a legacy row carries no clock; the project attributes are carried where the row has them
    assert {k: v for k, v in event.items() if k not in ("projectuuid", "projectslug")} == {
        k: v for k, v in expected.items() if k not in ("lamportclock", "nodeid")
    }
