def test_every_row_model_is_importable_and_strict() -> None:
    """Every row's ``model`` dotted path resolves to a real, frozen,
    ``extra='forbid'`` pydantic model (draft §5 Renata check (g))."""
    for row in SUPPORT_MATRIX:
        module_path, _, class_name = row.model.rpartition(".")
        assert module_path, f"{row.model!r} is not a dotted path"
        module = importlib.import_module(module_path)
        model_cls = getattr(module, class_name)
        assert model_cls.model_config.get("extra") == "forbid", row.model
        assert model_cls.model_config.get("frozen") is True, row.model


