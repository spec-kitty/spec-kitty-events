def test_old_consumer_fails_closed(monkeypatch: pytest.MonkeyPatch) -> None:
    """A pre-7.0 consumer that has not registered ``HarnessObservation``
    (e.g. because it monkeypatches/lacks the registry entry) gets a fail-closed
    ``ValueError`` from :func:`validate_event`, never a silent pass-through."""
    from spec_kitty_events.conformance import validators as validators_module

    monkeypatch.delitem(validators_module._EVENT_TYPE_TO_MODEL, "HarnessObservation")
    with pytest.raises(ValueError, match="Unknown event type"):
        validators_module.validate_event(
            {"kind": "presence", "harness": "claude", "session_id": "s1", "activity": "file_edit"},
            "HarnessObservation",
        )
